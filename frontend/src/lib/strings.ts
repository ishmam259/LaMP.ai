export type Locale = "en" | "bn";
const TABLE: Record<Locale, Record<StringKey, string>> = { en, bn };

/** One string in one language, with {name} filled in. */
export function $(key: StringKey, locale: Locale, vars?: Record<string, string | number>): string {
  const s = TABLE[locale][key] ?? en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

/* The choice is kept in this browser only; if storage is blocked it lasts until the page is reloaded. */
const KEY = "lamp-locale";
const EVENT = "lamp:locale";
let memory: Locale = "en";

function read(): Locale {
  try {
    const v = window.localStorage.getItem(KEY);
    return v === "bn" || v === "en" ? v : memory;
  } catch {
    return memory;
  }
}

function subscribe(onChange: () => void) {
  window.addEventListener(EVENT, onChange);
  window.addEventListener("storage", onChange);
  return () => {
    window.removeEventListener(EVENT, onChange);
    window.removeEventListener("storage", onChange);
  };
}

export function setLocale(locale: Locale) {
  memory = locale;
  try {
    window.localStorage.setItem(KEY, locale);
  } catch {
    /* private window or blocked storage: keep it in memory only */
  }
  window.dispatchEvent(new Event(EVENT));
}

/** The current language and t(key, vars) for it. The server always renders English. */
/** The chosen language outside React (for example in a request body). */
export function currentLocale(): Locale {
  return typeof window === "undefined" ? "en" : read();
}

export function useStrings() {
  const locale = useSyncExternalStore(subscribe, read, () => "en" as Locale);
  const t = useCallback((key: StringKey, vars?: Record<string, string | number>) => $(key, locale, vars), [locale]);
  return { locale, t };
}
